import { describe, expect, test } from 'bun:test';
import {
  findAiAttribution,
  findCommitAttribution,
  findPrAttribution,
} from '../../src/shared/ai-attribution.js';

const linesIn = (body: string) =>
  findAiAttribution([`s: x\n\n${body}`]).map((a) => a.line);

describe('findAiAttribution', () => {
  test('finds AI co-author trailers and "Generated with" lines in the body', () => {
    expect(
      findAiAttribution([
        'feat: add auth\n\nBody text.\n\nCo-authored-by: Claude <noreply@anthropic.com>',
        'fix: typo\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)',
        'chore: deps\n\nCo-authored-by: GitHub Copilot <copilot@github.com>\nAssisted-by: Cursor',
      ])
    ).toEqual([
      {
        where: 'commit-message',
        subject: 'feat: add auth',
        line: 'Co-authored-by: Claude <noreply@anthropic.com>',
      },
      {
        where: 'commit-message',
        subject: 'fix: typo',
        line: '🤖 Generated with [Claude Code](https://claude.com/claude-code)',
      },
      {
        where: 'commit-message',
        subject: 'chore: deps',
        line: 'Co-authored-by: GitHub Copilot <copilot@github.com>',
      },
      {
        where: 'commit-message',
        subject: 'chore: deps',
        line: 'Assisted-by: Cursor',
      },
    ]);
  });

  test('ignores the subject, human co-authors and generated-code notes that name no AI', () => {
    expect(
      findAiAttribution([
        'feat: support Claude models\n\nCo-authored-by: Ada Lovelace <ada@example.com>',
        'build: regenerate\n\nFiles generated by protoc.',
      ])
    ).toEqual([]);
  });

  const hits: Record<string, string> = {
    copilotBot:
      'Co-authored-by: copilot-swe-agent[bot] <198982749+Copilot@users.noreply.github.com>',
    devin:
      'Co-Authored-By: Devin AI <158243242+devin-ai-integration[bot]@users.noreply.github.com>',
    aider: 'Co-authored-by: aider (gpt-4o) <noreply@aider.chat>',
    codex: 'Co-authored-by: Codex <codex@openai.com>',
    gemini: 'Co-authored-by: Gemini <gemini@google.com>',
    chatgpt: 'Co-authored-by: ChatGPT <noreply@openai.com>',
    lowerCase: 'co-authored-by: claude <noreply@anthropic.com>',
    upperCase: 'CO-AUTHORED-BY: CLAUDE <NOREPLY@ANTHROPIC.COM>',
    session: 'Claude-Session: https://claude.ai/code/session_01ABC',
    kernelStyle: 'Assisted-by: Claude:claude-3-opus',
    amp: 'Co-authored-by: Amp <amp@ampcode.com>',
    ampThread: 'Amp-Thread-ID: https://ampcode.com/threads/T-1',
    jules:
      'Co-authored-by: google-labs-jules[bot] <161369871+google-labs-jules[bot]@users.noreply.github.com>',
    cline: 'Co-authored-by: Cline <cline@cline.bot>',
    opencode: 'Co-authored-by: opencode <noreply@opencode.ai>',
    generatedByTrailer: 'Generated-by: AI assistant',
    writtenWith: 'Written with Claude Code',
  };
  for (const [name, line] of Object.entries(hits)) {
    test(`finds ${name}`, () => expect(linesIn(line)).toEqual([line]));
  }

  test('finds an indented trailer and reports it trimmed', () => {
    expect(
      linesIn('    Co-authored-by: Claude <noreply@anthropic.com>')
    ).toEqual(['Co-authored-by: Claude <noreply@anthropic.com>']);
  });

  const humans: Record<string, string> = {
    'a human named Claude who signs off':
      'Signed-off-by: Claude Dupont <claude.dupont@example.fr>',
    'a human co-author named Claude Monet':
      'Co-authored-by: Claude Monet <monet@example.com>',
    'a "Fix:" line that mentions a cursor':
      'Fix: the db cursor is closed before the last row',
    'a stack trace line': 'Error: Cursor closed while iterating',
    'a note that mentions an AI SDK':
      'Note: callers of the OpenAI SDK need the new header',
  };
  for (const [name, line] of Object.entries(humans)) {
    test(`ignores ${name}`, () => expect(linesIn(line)).toEqual([]));
  }

  test('ignores a trailer-shaped line outside the last paragraph', () => {
    expect(
      linesIn(
        'Co-authored-by: Claude <noreply@anthropic.com>\n\nMore text after it.'
      )
    ).toEqual([]);
  });
});

describe('findCommitAttribution', () => {
  test('reports an AI author and committer by name or email', () => {
    expect(
      findCommitAttribution([
        {
          message: 'feat: x',
          author: 'Copilot <198982749+Copilot@users.noreply.github.com>',
          committer: 'Ada Lovelace <ada@example.com>',
        },
        {
          message: 'feat: y\n\nCo-authored-by: Claude <noreply@anthropic.com>',
          author: 'Ada Lovelace <ada@example.com>',
          committer: 'Claude <noreply@anthropic.com>',
        },
      ])
    ).toEqual([
      {
        where: 'commit-author',
        subject: 'feat: x',
        line: 'Copilot <198982749+Copilot@users.noreply.github.com>',
      },
      {
        where: 'commit-committer',
        subject: 'feat: y',
        line: 'Claude <noreply@anthropic.com>',
      },
      {
        where: 'commit-message',
        subject: 'feat: y',
        line: 'Co-authored-by: Claude <noreply@anthropic.com>',
      },
    ]);
  });

  test('ignores a human author named Claude', () => {
    expect(
      findCommitAttribution([
        {
          message: 'feat: x',
          author: 'Claude Monet <claude@monet.example>',
          committer: 'Claude Monet <claude@monet.example>',
        },
      ])
    ).toEqual([]);
  });
});

describe('findPrAttribution', () => {
  test('reports AI lines in the PR title and the PR body trailers', () => {
    expect(
      findPrAttribution(
        'Generated with Claude Code: add auth',
        'Adds auth.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nCo-authored-by: Claude <noreply@anthropic.com>'
      )
    ).toEqual([
      { where: 'pr-title', line: 'Generated with Claude Code: add auth' },
      {
        where: 'pr-body',
        line: '🤖 Generated with [Claude Code](https://claude.com/claude-code)',
      },
      {
        where: 'pr-body',
        line: 'Co-authored-by: Claude <noreply@anthropic.com>',
      },
    ]);
  });

  test('scans only the text that is published', () => {
    expect(
      findPrAttribution(
        undefined,
        'Co-authored-by: Claude <noreply@anthropic.com>'
      )
    ).toEqual([
      {
        where: 'pr-body',
        line: 'Co-authored-by: Claude <noreply@anthropic.com>',
      },
    ]);
    expect(findPrAttribution('feat: add auth', undefined)).toEqual([]);
  });
});
